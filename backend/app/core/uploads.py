import uuid
import io
import zipfile
from pathlib import Path

from fastapi import HTTPException, UploadFile, status

# backend/app/core/uploads.py -> backend/uploads/support/
UPLOAD_ROOT = Path(__file__).resolve().parent.parent.parent / "uploads" / "support"

MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024  # 10 MB
MAX_FILES_PER_MESSAGE = 3

# Allow-list, not a block-list — only these extensions/content-types are
# ever accepted, so an unexpected/dangerous type (e.g. an executable) is
# rejected by default rather than needing to be explicitly blocked.
ALLOWED_EXTENSIONS: dict[str, str] = {
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".pdf": "application/pdf",
    ".doc": "application/msword",
    ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    ".txt": "text/plain",
}


def _content_matches_extension(ext: str, contents: bytes) -> bool:
    if ext in (".jpg", ".jpeg"):
        return contents.startswith(b"\xff\xd8\xff")
    if ext == ".png":
        return contents.startswith(b"\x89PNG\r\n\x1a\n")
    if ext == ".gif":
        return contents.startswith((b"GIF87a", b"GIF89a"))
    if ext == ".webp":
        return len(contents) >= 12 and contents[:4] == b"RIFF" and contents[8:12] == b"WEBP"
    if ext == ".pdf":
        return contents.startswith(b"%PDF-")
    if ext == ".doc":
        return contents.startswith(b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1")
    if ext == ".docx":
        try:
            with zipfile.ZipFile(io.BytesIO(contents)) as archive:
                names = set(archive.namelist())
            return "[Content_Types].xml" in names and "word/document.xml" in names
        except (OSError, ValueError, zipfile.BadZipFile):
            return False
    if ext == ".txt":
        try:
            decoded = contents.decode("utf-8-sig")
        except UnicodeDecodeError:
            return False
        return all(char.isprintable() or char in "\r\n\t" for char in decoded)
    return False


async def read_upload_limited(file: UploadFile, max_bytes: int) -> bytes:
    """Read at most one byte beyond the limit before validation/persistence."""
    contents = await file.read(max_bytes + 1)
    if len(contents) > max_bytes:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST,
                            detail=f"File is too large. Maximum size is {max_bytes // (1024 * 1024)}MB.")
    return contents


def save_upload(file: UploadFile, contents: bytes) -> tuple[str, str, str, int]:
    """Validates and persists one uploaded file to local disk.

    Returns (storage_reference, file_name, file_type, file_size). The file
    is written under a random UUID name — the caller's original filename is
    kept only for display, never used to build a disk path, so a malicious
    filename (e.g. containing "../") can't escape the upload directory or
    collide with another file.
    """
    original_name = file.filename or "upload"
    ext = Path(original_name).suffix.lower()

    if ext not in ALLOWED_EXTENSIONS:
        allowed = ", ".join(sorted(ALLOWED_EXTENSIONS))
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"File type not allowed. Accepted types: {allowed}",
        )

    if len(contents) > MAX_FILE_SIZE_BYTES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"File is too large. Maximum size is {MAX_FILE_SIZE_BYTES // (1024 * 1024)}MB.",
        )

    if not contents:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Uploaded file is empty.")

    if not _content_matches_extension(ext, contents):
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST,
                            detail="File content does not match its extension or is unsupported.")

    UPLOAD_ROOT.mkdir(parents=True, exist_ok=True)
    storage_reference = f"{uuid.uuid4().hex}{ext}"
    (UPLOAD_ROOT / storage_reference).write_bytes(contents)

    file_type = ALLOWED_EXTENSIONS[ext]
    return storage_reference, original_name[:255], file_type, len(contents)


def get_upload_path(storage_reference: str) -> Path:
    """Resolves a stored attachment's disk path. storage_reference is always
    a UUID + known extension generated by save_upload — never user input —
    so no path-traversal check is needed here, but resolve+require the
    upload root as a defensive boundary anyway."""
    path = (UPLOAD_ROOT / storage_reference).resolve()
    if UPLOAD_ROOT.resolve() not in path.parents:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Attachment not found")
    return path


def delete_upload(storage_reference: str) -> None:
    path = UPLOAD_ROOT / storage_reference
    if path.exists():
        path.unlink()


# ---------------------------------------------------------------------------
# Profile photos — a separate root and a stricter, image-only allow-list from
# support attachments above, since these are served back to any authenticated
# user (not just the ticket's own participants).
# ---------------------------------------------------------------------------

PROFILE_PHOTO_ROOT = Path(__file__).resolve().parent.parent.parent / "uploads" / "profile_photos"

MAX_PHOTO_SIZE_BYTES = 5 * 1024 * 1024  # 5 MB

ALLOWED_PHOTO_EXTENSIONS: dict[str, str] = {
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
    ".gif": "image/gif",
}


def save_profile_photo(file: UploadFile, contents: bytes) -> str:
    """Validates and persists one profile photo. Returns the storage
    reference (a random UUID + extension — never the caller's filename, for
    the same path-traversal reason as save_upload)."""
    original_name = file.filename or "photo"
    ext = Path(original_name).suffix.lower()

    if ext not in ALLOWED_PHOTO_EXTENSIONS:
        allowed = ", ".join(sorted(ALLOWED_PHOTO_EXTENSIONS))
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"File type not allowed. Accepted types: {allowed}",
        )

    if len(contents) > MAX_PHOTO_SIZE_BYTES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"File is too large. Maximum size is {MAX_PHOTO_SIZE_BYTES // (1024 * 1024)}MB.",
        )

    if not contents:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Uploaded file is empty.")

    if not _content_matches_extension(ext, contents):
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST,
                            detail="Photo content does not match its extension or is unsupported.")

    PROFILE_PHOTO_ROOT.mkdir(parents=True, exist_ok=True)
    storage_reference = f"{uuid.uuid4().hex}{ext}"
    (PROFILE_PHOTO_ROOT / storage_reference).write_bytes(contents)
    return storage_reference


def get_profile_photo_path(storage_reference: str) -> Path:
    path = (PROFILE_PHOTO_ROOT / storage_reference).resolve()
    if PROFILE_PHOTO_ROOT.resolve() not in path.parents:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Profile photo not found")
    return path


def delete_profile_photo(storage_reference: str) -> None:
    path = PROFILE_PHOTO_ROOT / storage_reference
    if path.exists():
        path.unlink()


