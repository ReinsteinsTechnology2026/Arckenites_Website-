"""Where recording files live.

Two distinct things, never confused:

* `StagingStore` — LOCAL disk staging on persistent storage controlled by
  Arckenites. This is NOT OneDrive. It is where the media server writes a
  recording and where it is verified; a verified local copy is kept until the
  remote upload is itself verified. Nothing is deleted automatically.
* `OneDriveStore` (app/core/onedrive_store.py) — the final destination. It
  reports itself NOT READY until upload access and the destination have been
  configured, so nothing is "published" on the strength of a flag alone.

Every filename here is generated by the server; no user input ever reaches a
filesystem path, and resolution refuses anything that escapes the root.
"""
import hashlib
import os
import shutil
import uuid
from pathlib import Path

from app.config import settings

REPO_ROOT = Path(__file__).resolve().parents[3]
CHUNK = 1024 * 1024


class StorageError(Exception):
    pass


def new_staging_key() -> str:
    """A fresh, unguessable, filesystem-safe key. Never derived from user input."""
    return f"incoming/{uuid.uuid4().hex}.mp4"


class StagingStore:
    provider = "LOCAL_STAGING"

    def __init__(self, root: str | Path | None = None):
        self.root = Path(root if root is not None else settings.recording_staging_dir)

    def readiness(self) -> tuple[bool, str | None]:
        if not str(self.root) or str(self.root) == ".":
            return False, "Recording storage isn't configured."
        if not self.root.is_absolute() or not self.root.is_dir():
            return False, "Recording storage isn't available."
        resolved = self.root.resolve()
        if resolved == REPO_ROOT or REPO_ROOT in resolved.parents:
            return False, "Recording storage is misconfigured."
        if not os.access(resolved, os.W_OK):
            return False, "Recording storage isn't writable."
        if self.free_bytes() < settings.recording_min_free_gb * 1024 ** 3:
            return False, "Recording storage is nearly full."
        return True, None

    def free_bytes(self) -> int:
        return shutil.disk_usage(self.root.resolve()).free

    def path_for(self, key: str) -> Path:
        """Absolute path for a storage key, refusing traversal and symlink escapes."""
        if not key or key.startswith(("/", "\\")) or ".." in Path(key).parts:
            raise StorageError("invalid storage key")
        root = self.root.resolve()
        path = (root / key).resolve()
        if root not in path.parents:
            raise StorageError("storage key escapes the storage root")
        return path

    def exists_nonempty(self, key: str) -> bool:
        try:
            path = self.path_for(key)
        except StorageError:
            return False
        return path.is_file() and path.stat().st_size > 0

    @staticmethod
    def sha256_of(path: Path) -> str:
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            for block in iter(lambda: handle.read(CHUNK), b""):
                digest.update(block)
        return digest.hexdigest()
