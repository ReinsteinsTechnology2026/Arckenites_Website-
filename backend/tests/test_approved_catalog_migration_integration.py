@unittest.skipUnless(isolated_postgres_enabled(), "Requires marked disposable PostgreSQL")
class ApprovedCatalogMigrationPostgresTests(unittest.TestCase):
    def setUp(self):
        self.schema = "catalog_case_" + uuid4().hex
        with engine.begin() as connection:
            connection.execute(text(f"CREATE SCHEMA {self.schema}"))
            connection.execute(text(f"""
                CREATE TABLE {self.schema}.programs (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name varchar(200) NOT NULL,
                    slug varchar(80) NOT NULL UNIQUE,
                    code varchar(40) UNIQUE,
                    category varchar(120),
                    mode text NOT NULL DEFAULT 'offline',
                    status text NOT NULL DEFAULT 'active'
                )
            """))
            connection.execute(text(f"INSERT INTO {self.schema}.programs (id,name,slug,code) VALUES "
                                    "(1,'Official Certification Program','official_certification','OCP-01'),"
                                    "(3,'Institutional Program','institutional','INS-01')"))
            connection.execute(text(f"ALTER TABLE {self.schema}.programs ALTER COLUMN id RESTART WITH 4"))
        self.addCleanup(self._drop_schema)

    def _drop_schema(self):
        with engine.begin() as connection:
            connection.execute(text(f"DROP SCHEMA {self.schema} CASCADE"))

    def _run(self, *, expected_error=None):
        with engine.begin() as connection:
            connection.execute(text(f"SET LOCAL search_path TO {self.schema}, public"))
            with Operations.context(MigrationContext.configure(connection)):
                if expected_error is None:
                    migration.upgrade()
                else:
                    with self.assertRaisesRegex(RuntimeError, expected_error):
                        migration.upgrade()

    def _rows(self):
        with engine.connect() as connection:
            return connection.execute(text(f"SELECT id,name,slug,code,status FROM {self.schema}.programs ORDER BY id")).mappings().all()

    def test_fresh_parent_catalog_inserts_only_missing_rows_with_database_ids(self):
        before = [dict(row) for row in self._rows()]
        self._run()
        rows = self._rows()
        self.assertEqual(len(rows), 4)
        self.assertEqual([dict(row) for row in rows[:2]], before)
        self.assertEqual({row["name"] for row in rows[2:]},
                         {"Freshers Job Hack Program", "Certificational Program"})
        self.assertEqual({row["status"] for row in rows[2:]}, {"active"})
        self.assertTrue(all(row["id"] > 3 for row in rows[2:]))

    def test_existing_canonical_row_is_preserved_and_reexecution_is_noop(self):
        with engine.begin() as connection:
            connection.execute(text(f"""INSERT INTO {self.schema}.programs
                (id,name,slug,code) VALUES
                (42,'Freshers Job Hack Program','freshers_job_hack','FJH-01')"""))
        self._run()
        first = [dict(row) for row in self._rows()]
        self.assertEqual(len(first), 4)
        self.assertEqual(next(row for row in first if row["name"] == "Freshers Job Hack Program")["id"], 42)
        self._run()
        self.assertEqual([dict(row) for row in self._rows()], first)

    def test_ambiguous_name_blocks_both_inserts(self):
        with engine.begin() as connection:
            connection.execute(text(f"""INSERT INTO {self.schema}.programs (name,slug,code) VALUES
                ('Freshers Job Hack Program','other_freshers','OTHER-1'),
                ('  FRESHERS   JOB HACK PROGRAM  ','other_freshers_2','OTHER-2')"""))
        before = [dict(row) for row in self._rows()]
        self._run(expected_error="Ambiguous approved program name")
        self.assertEqual([dict(row) for row in self._rows()], before)

    def test_slug_or_code_conflicts_block_both_inserts(self):
        for field, value in (("slug", "certificational"), ("code", "cfp-01")):
            with self.subTest(field=field):
                with engine.begin() as connection:
                    connection.execute(text(f"DELETE FROM {self.schema}.programs WHERE id NOT IN (1,3)"))
                    connection.execute(text(f"INSERT INTO {self.schema}.programs (name,slug,code) "
                                            f"VALUES ('Unrelated', :slug, :code)"),
                                       {"slug": value if field == "slug" else "unrelated",
                                        "code": value if field == "code" else "UNREL-1"})
                before = [dict(row) for row in self._rows()]
                self._run(expected_error="Slug or code belongs to another record")
                self.assertEqual([dict(row) for row in self._rows()], before)

    def test_existing_name_with_other_identity_or_inactive_status_blocks(self):
        with engine.begin() as connection:
            connection.execute(text(f"""INSERT INTO {self.schema}.programs
                (name,slug,code,status) VALUES
                ('Certificational Program','different_certification','DIFF-1','inactive')"""))
        before = [dict(row) for row in self._rows()]
        self._run(expected_error="Existing approved program identity differs")
        self.assertEqual([dict(row) for row in self._rows()], before)

    def test_missing_institutional_blocks_both_inserts(self):
        with engine.begin() as connection:
            connection.execute(text(f"DELETE FROM {self.schema}.programs WHERE id=3"))
        before = [dict(row) for row in self._rows()]
        self._run(expected_error="requires one active Institutional Program")
        self.assertEqual([dict(row) for row in self._rows()], before)

    def test_downgrade_is_noop_and_reupgrade_creates_no_duplicates(self):
        self._run()
        after_upgrade = [dict(row) for row in self._rows()]
        self.assertEqual(len(after_upgrade), 4)
        with engine.begin() as connection:
            connection.execute(text(f"SET LOCAL search_path TO {self.schema}, public"))
            with Operations.context(MigrationContext.configure(connection)):
                migration.downgrade()
        self.assertEqual([dict(row) for row in self._rows()], after_upgrade)
        self._run()
        self.assertEqual([dict(row) for row in self._rows()], after_upgrade)


@unittest.skipUnless(isolated_postgres_enabled(), "Requires marked disposable PostgreSQL")
class ApprovedCatalogApiPostgresTests(unittest.TestCase):
    @staticmethod
    def _deactivate_actor(actor_id):
        # Other integration tests count active Super Admins; leave none behind.
        with Session(bind=engine) as db:
            db.execute(text("UPDATE users SET is_active = false WHERE id = :id"), {"id": actor_id})
            db.commit()

    def test_options_and_student_assignment_for_all_three(self):
        with Session(bind=engine) as db:
            revision = db.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
            backend = Path(__file__).resolve().parents[1]
            config = Config(str(backend / "alembic.ini"))
            config.set_main_option("script_location", str(backend / "alembic"))
            heads = ScriptDirectory.from_config(config).get_heads()
            self.assertEqual([revision], heads)
            role = db.scalar(select(AdminRole).where(AdminRole.slug == SUPER_ADMIN_SLUG))
            self.assertIsNotNone(role)
            actor = User(username=f"catalog-qa-{uuid4().hex}@example.test", password_hash="unused",
                         full_name="Catalog QA Admin", role=RoleEnum.admin,
                         admin_role_id=role.id, is_active=True)
            db.add(actor)
            db.flush()
            actor_id = actor.id
            self.addCleanup(self._deactivate_actor, actor_id)
            jti = uuid4()
            token, expires = create_access_token(actor_id, "admin", jti)
            db.add(AuthSession(id=jti, user_id=actor_id, expires_at=expires))
            db.commit()

        client = TestClient(app)
        headers = {"Authorization": f"Bearer {token}"}
        options = client.get("/api/admin/students/program-options", headers=headers)
        self.assertEqual(options.status_code, 200, options.text)
        self.assertEqual([row["name"] for row in options.json()],
                         ["Institutional Program", "Freshers Job Hack Program", "Certificational Program"])
        self.assertEqual(len({row["id"] for row in options.json()}), 3)
        self.assertEqual(len({row["slug"] for row in options.json()}), 3)

        legacy_sql = text("SELECT md5(coalesce(string_agg(p::text, ';' ORDER BY id), '')), count(*) FROM programs p "
                          "WHERE lower(name) NOT IN ('institutional program','freshers job hack program','certificational program')")
        with Session(bind=engine) as db:
            legacy_before = tuple(db.execute(legacy_sql).one())
            legacy_ids = [r[0] for r in db.execute(text(
                "SELECT id FROM programs WHERE lower(name) NOT IN "
                "('institutional program','freshers job hack program','certificational program') ORDER BY id"))]
        self.assertGreaterEqual(len(legacy_ids), 1)

        listing = client.get("/api/admin/programs", headers=headers)
        self.assertEqual(listing.status_code, 200, listing.text)
        self.assertEqual([row["name"] for row in listing.json()], [row["name"] for row in options.json()])
        self.assertEqual({row["id"] for row in listing.json()}, {row["id"] for row in options.json()})
        stats = client.get("/api/admin/programs/stats", headers=headers).json()
        self.assertEqual(stats["total_programs"], 3)
        self.assertIsNone(stats["catalog_notice"])
        created = client.post("/api/admin/programs", headers=headers, json={"name": "Brand New Program"})
        self.assertEqual(created.status_code, 403, created.text)
        for legacy_id in legacy_ids:
            self.assertEqual(client.get(f"/api/admin/programs/{legacy_id}", headers=headers).status_code, 404)
            self.assertEqual(client.patch(f"/api/admin/programs/{legacy_id}", headers=headers,
                                          json={"status": "inactive"}).status_code, 404)
        with Session(bind=engine) as db:
            self.assertEqual(tuple(db.execute(legacy_sql).one()), legacy_before)

        with patch("app.api.routes_admin_students.send_student_credentials",
                   return_value=CredentialEmailOut(credential_email_sent=False, detail="QA email disabled")) as send:
            for row in options.json():
                email = f"catalog-qa-{uuid4().hex}@example.test"
                response = client.post("/api/admin/students", headers=headers, json={
                    "full_name": "Catalog QA Student", "email": email,
                    "temp_password": "CatalogQaPassword123", "program_id": row["id"],
                })
                self.assertEqual(response.status_code, 201, response.text)
                with Session(bind=engine) as db:
                    enrollment = db.scalar(select(ProgramEnrollment).where(
                        ProgramEnrollment.student_id == response.json()["id"]))
                    self.assertIsNotNone(enrollment)
                    self.assertEqual(enrollment.program_id, row["id"])
            self.assertEqual(send.call_count, 3)


if __name__ == "__main__":
    unittest.main()
